import { expect, test } from "bun:test";
import { part1, part2 } from "./index.ts";

const sample = `............
........0...
.....0......
.......0....
....0.......
......A.....
............
............
........A...
.........A..
............
............`;

test("finds antinodes on shared lines", () => {
	expect(part1(sample)).toBe(14);
	expect(part2(sample)).toBe(34);
});

test("includes intermediate lattice points", () => {
	expect(part2("A...A")).toBe(5);
});
