const alphabet = new Map<string, string>();
for (const font of fonts) {
	for (const [letter, pattern] of Object.entries(font))
		alphabet.set(pattern, letter);
}

export function decodeLetters(rows: string[]): string {
	const display = rows.join("\n");
	if (rows.length === 0) return display;
	const pixels = rows.map((row) =>
		row.replaceAll("█", "#").replaceAll(" ", "."),
	);
	const width = Math.max(...pixels.map((row) => row.length));
	let result = "";
	let start = 0;
	for (let x = 0; x <= width; x++) {
		if (pixels.some((row) => row[x] === "#")) continue;
		if (x > start) {
			const shape = pixels
				.map((row) => row.padEnd(width, ".").slice(start, x))
				.join(" ");
			const letter = alphabet.get(shape);
			if (!letter) return display;
			result += letter;
		}
		start = x + 1;
	}
	return result || display;
}
